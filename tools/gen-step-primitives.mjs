/**
 * Regenerates `src/simulation/eucStepPrimitives.ts`: the controller's
 * primitive transaction fields and the unrolled copier
 * `EucController.copyMutableStateFrom` runs for every checkpoint and rollback.
 *
 *   node tools/gen-step-primitives.mjs           rewrite the file from a fresh controller
 *   node tools/gen-step-primitives.mjs --check   exit 1 if the file is stale; write nothing
 *
 * **When to run it.** After adding, removing or renaming an `EucController`
 * field. The controller refuses its first transaction with "EUC transaction
 * primitive list is stale" until the list agrees with its fields again, and
 * `src/simulation/eucStepPrimitives.test.ts` fails with the same advice. A new
 * object-valued field is not a primitive: it needs its own explicit copy rule
 * in `copyMutableStateFrom` and a place in `EUC_STEP_REFERENCE_FIELDS`, and
 * this tool refuses it ("needs an explicit state copy") until it has both.
 *
 * **Where the list comes from.** The same classification the controller
 * applies at run time: `eucStepPrimitiveFieldsOf` and
 * `EUC_STEP_REFERENCE_FIELDS` are imported from `EucController.ts`, never
 * restated here, so this tool and the run-time guard cannot disagree about
 * which fields are references. Field order is declaration order, which keeps
 * the output stable from run to run.
 *
 * **Why a generated copier at all** (perf-actions 2026-10-17, item
 * "controller"). A loop of `to[key] = from[key]` over some 160 names is a keyed
 * access the engine cannot specialise; one named assignment per field is. The
 * set of copied fields is unchanged, so every checkpoint is bit-identical to
 * the loop's. Measuring that is the controller parity harness's job; this
 * tool only writes text and reports a field count.
 */

import { readFileSync, realpathSync, writeFileSync } from 'node:fs';
import { dirname, join, relative, resolve } from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const target = join(root, 'src', 'simulation', 'eucStepPrimitives.ts');
const shown = relative(root, target).split('\\').join('/');

const { EucController, eucStepPrimitiveFieldsOf } = await import(
  pathToFileURL(join(root, 'src', 'simulation', 'EucController.ts')).href);

/** Level, paved and empty: a construction site for a controller, nothing more. */
const flat = {
  sampleGround(_x, _z, out) {
    out.height = 0; out.normal.x = 0; out.normal.y = 1; out.normal.z = 0;
    out.surface = 'pavement'; out.offCourse = false; return out;
  },
  raycast() { return null; },
};

/** The whole file for one ordered field list. Pure, so `--check` compares text. */
export function renderEucStepPrimitives(fields) {
  const lines = [
    '/**',
    " * The controller's primitive transaction state, copied by named property.",
    ' * Generated by `node tools/gen-step-primitives.mjs` from a fresh',
    " * `EucController`'s own fields less `EUC_STEP_REFERENCE_FIELDS`; do not edit",
    ' * by hand. `copyMutableStateFrom` still classifies the fields once per',
    ' * process and refuses an unclassified reference, then refuses a set that',
    ' * differs from this list, so a new clock or latch cannot silently drop out',
    ' * of a checkpoint: add or remove a controller field, then regenerate. The',
    ' * copier is one monomorphic assignment per name (perf-actions 2026-10-17,',
    ' * item "controller"). Plain data: no three import.',
    ' */',
    'export const EUC_STEP_PRIMITIVE_FIELDS = Object.freeze([',
  ];
  for (let i = 0; i < fields.length; i += 6) lines.push(`  ${fields.slice(i, i + 6).map((k) => `'${k}'`).join(', ')},`);
  lines.push(
    '] as const);',
    'export type EucStepPrimitiveField = typeof EUC_STEP_PRIMITIVE_FIELDS[number];',
    'export type EucStepPrimitiveState = { -readonly [K in EucStepPrimitiveField]: unknown };',
    '',
    '/** Exactly `for (const key of EUC_STEP_PRIMITIVE_FIELDS) to[key] = from[key]`, unrolled. */',
    'export function copyEucStepPrimitives(to: EucStepPrimitiveState, from: EucStepPrimitiveState): void {',
  );
  for (const k of fields) lines.push(`  to.${k} = from.${k};`);
  lines.push('}');
  return `${lines.join('\n')}\n`;
}

/** The ordered primitive fields of a freshly constructed controller. */
export function discoverEucStepPrimitiveFields() {
  const fields = eucStepPrimitiveFieldsOf(new EucController(flat));
  for (const k of fields) if (!/^[A-Za-z_$][\w$]*$/.test(k)) throw new Error(`gen-step-primitives: ${k} is not a plain identifier`);
  return fields;
}

/**
 * Run as the main module? Node resolves the main module through symlinks
 * (`import.meta.url` is the real path) but leaves `process.argv[1]` as typed,
 * so comparing the two raw would skip the whole tool, `--check` included, and
 * exit 0 when it is run through a symlinked path. Compare real paths.
 */
function invokedAsMain() {
  if (!process.argv[1]) return false;
  try {
    return realpathSync(resolve(process.argv[1])) === realpathSync(fileURLToPath(import.meta.url));
  } catch {
    return false;
  }
}

if (invokedAsMain()) {
  const args = process.argv.slice(2);
  const unknown = args.filter((a) => a !== '--check');
  if (unknown.length) {
    console.error(`gen-step-primitives: unknown argument ${unknown.join(' ')}\nusage: node tools/gen-step-primitives.mjs [--check]`);
    process.exit(2);
  }
  const fields = discoverEucStepPrimitiveFields();
  const text = renderEucStepPrimitives(fields);
  let current = null;
  try { current = readFileSync(target, 'utf8'); } catch { /* absent: written below, stale under --check */ }
  if (args.includes('--check')) {
    if (current === text) {
      console.log(`gen-step-primitives: ${shown} is current (${fields.length} primitive fields).`);
    } else {
      console.error(`gen-step-primitives: ${shown} is stale; run node tools/gen-step-primitives.mjs`);
      process.exit(1);
    }
  } else if (current === text) {
    console.log(`gen-step-primitives: ${shown} already current (${fields.length} primitive fields).`);
  } else {
    writeFileSync(target, text);
    console.log(`gen-step-primitives: wrote ${shown} (${fields.length} primitive fields).`);
  }
}
